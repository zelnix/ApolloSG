export function luddishShared() {
  return {
    note: "Generated by frontend/scripts/exportLuddish.ts from the app's Higgins Luddish. Do not edit by hand.",
    plainSwaps: PLAIN_SWAPS.map(([formal, plain]) => [formal, plain]),
    plainTerms: COMPILED.filter((t) => t.plain).map((t) => ({ match: t.match, exactCase: !!t.exactCase, one: t.plain!.one, many: t.plain!.many ?? null })),
    tone: { CERTAINTY_ADDED: CERTAINTY, SAFETY_CLAIM_ADDED: SAFETY, SEVERITY_SOFTENED: SOFTENERS, SEVERITY_ESCALATED: ESCALATORS },
    parity: PARITY_CORPUS.map(([text, strong]) => ({ text, strong, out: luddishText(text, strong) })),
  };
}
